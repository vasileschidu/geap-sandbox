// Builds css/shell-nav.css = the BO side-navigation item rules, taken verbatim and in order from css/e-permits-shell.css
// (the single source). Pages that need the BO sidebar items without the BO shell (EVO Cabinet v2 menu) load the subset.
// Kept: rules whose every selector is a `.e-permits-shell__nav…` / `.e-permits-shell__group-label` part. Left in the BO
// file only: the collapsed sidebar, tooltips, the per-item icon masks (`[data-nav-id]` — each product names its own).
// Run after any change to the nav rules in css/e-permits-shell.css:  node tools/css/extract-shell-nav.mjs
import fs from "node:fs";

const SRC = "css/e-permits-shell.css";
const OUT = "css/shell-nav.css";
const css = fs.readFileSync(SRC, "utf8");

// top-level blocks: [prelude, body]
function blocks(text) {
  const out = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf("{", i);
    if (open < 0) break;
    let depth = 1;
    let j = open + 1;
    while (j < text.length && depth) { if (text[j] === "{") depth++; else if (text[j] === "}") depth--; j++; }
    out.push([text.slice(i, open).replace(/\/\*[\s\S]*?\*\//g, "").trim(), text.slice(open + 1, j - 1)]);
    i = j;
  }
  return out;
}
const keep = (prelude) => {
  const selectors = prelude.split(",").map((s) => s.trim()).filter(Boolean);
  return selectors.length > 0 && selectors.every((s) =>
    /^\.e-permits-shell__(nav|group-label|profile-role-(card|copy|label|name))/.test(s)
    && !/is-collapsed|__nav-tooltip|__nav--legacy|__nav-group--config|\[data-|__content|__collapse/.test(s));
};
const rule = (prelude, body, pad = "") => `${pad}${prelude.replace(/\s*\n\s*/g, `\n${pad}`)} {${body.replace(/\s+$/, "")}\n${pad}}\n`;

const parts = [];
for (const [prelude, body] of blocks(css)) {
  if (prelude.startsWith("@media")) {
    const inner = blocks(body).filter(([p]) => keep(p)).map(([p, b]) => rule(p, b, "  "));
    if (inner.length) parts.push(`${prelude} {\n${inner.join("\n")}}\n`);
  } else if (!prelude.startsWith("@") && keep(prelude)) parts.push(rule(prelude, body));
}
const head = `/* =====================================================================================
   BO side navigation — the item rules, shared (shell-nav-v1, 2026-11-17; components.md › „BO side navigation”).
   GENERATED by tools/css/extract-shell-nav.mjs from css/e-permits-shell.css — do not edit here: change the BO file and
   run the tool. Verbatim, same order, so the items measure exactly as in the Back Office:
   nav.e-permits-shell__nav.e-permits-shell__nav--specialist › .e-permits-shell__nav-group › p|h2.e-permits-shell__group-label
   + ul.e-permits-shell__nav-list › li › a.e-permits-shell__nav-link(.is-active) › .e-permits-shell__nav-icon (20, a CSS
   mask per [data-nav-id], set by the page that owns the menu) + .e-permits-shell__nav-text + .e-permits-shell__nav-badge;
   and the account role card (.e-permits-shell__profile-role-card › __profile-role-copy › __profile-role-name / -label) —
   the Cabinet v2 identity block on top of the menu (cab2-s1-v1).
   Loaded by the EVO Cabinet v2 menu (cabinet-evo/cab2-shell.css adds the surface and the icon masks). The BO pages keep
   loading css/e-permits-shell.css only.
   ===================================================================================== */\n\n`;
fs.writeFileSync(OUT, head + parts.join("\n"));
console.log(`${OUT}: ${parts.length} rules`);
